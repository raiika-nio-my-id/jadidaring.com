#!/usr/bin/env python3
"""data/words.tsv -> data/audio/<i>.mp3 (edge-tts zh-CN-XiaoxiaoNeural, trimmed, mono 22 kHz 24 kbps) -> src/bank.js"""
import os, sys, json, base64, subprocess, hashlib
R = os.path.join(os.path.dirname(__file__), '..'); A = os.path.join(R, 'data', 'audio'); os.makedirs(A, exist_ok=True)
VOICE = 'zh-CN-XiaoxiaoNeural'; TTS = os.path.join(R, '.venv', 'bin', 'edge-tts')
rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(R, 'data', 'words.tsv'), encoding='utf-8') if l.strip() and not l.startswith('#')]
words = []; seen = set()
for i, r in enumerate(rows):
    hz, py, ar, cat, ehz, epy, ear, tip = r
    syl = py.split(' ')
    assert len(syl) == len(hz), ('syllables != hanzi', hz, py)
    assert hz not in seen and ar not in seen, ('dup', hz, ar); seen.add(hz); seen.add(ar)
    txt = hz + '。' if len(hz) == 1 else hz
    h = hashlib.md5((VOICE + txt).encode()).hexdigest()[:8]; f = os.path.join(A, h + '.mp3')
    if not os.path.exists(f):
        raw = f + '.raw.mp3'
        subprocess.run([TTS, '--text', txt, '--voice', VOICE, '--rate=-10%', '--write-media', raw], check=True, capture_output=True)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', raw, '-af', 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.08', '-ac', '1', '-ar', '22050', '-b:a', '24k', f], check=True); os.remove(raw)
    words.append({'hz': hz, 'py': syl, 'ar': ar, 'c': cat, 'ex': [ehz, epy, ear], 'tip': tip, 'au': base64.b64encode(open(f, 'rb').read()).decode()})
js = '// generated by tools/mkbank.py from data/words.tsv; audio: edge-tts %s\nconst BANK = %s;\n' % (VOICE, json.dumps(words, ensure_ascii=False, separators=(',', ':')))
open(os.path.join(R, 'src', 'bank.js'), 'w', encoding='utf-8').write(js)
print('bank', len(words), 'words', len(js.encode()), 'bytes; audio', sum(len(w['au']) for w in words))
