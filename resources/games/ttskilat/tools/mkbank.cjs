// data/bank.txt -> src/bank.js (window.TTSBank: [[word, clue, cat, diff]])
const fs = require('fs'), path = require('path');
const seen = new Set(), out = [];
for (const ln of fs.readFileSync(path.join(__dirname, '..', 'data', 'bank.txt'), 'utf8').split('\n')) {
  if (!ln.trim() || ln.startsWith('#')) continue; const [w, c, cat, d] = ln.split('|');
  if (!/^[A-Z]{3,9}$/.test(w) || seen.has(w)) continue; seen.add(w); out.push([w, c, cat, +d]);
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'bank.js'), '/* generated by tools/mkbank.js from data/bank.txt */\n(function (root) { root.TTSBank = ' + JSON.stringify(out) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n');
console.log('bank', out.length);
